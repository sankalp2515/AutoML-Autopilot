"""Baseline + deterministic profiler.

Produces the only facts the planner may reason over. Each Finding records the
method that computed it and how many rows it used. Nothing here is generated by
a model, and no raw rows leave this module (findings hold aggregates only).
"""
from __future__ import annotations

import re
from typing import Any

import numpy as np
import pandas as pd

from app.autopilot import mlcore
from app.autopilot.schemas import Finding
from app.autopilot.workspace import Workspace

PSI_WARN, PSI_CRIT = 0.10, 0.25
MIN_ROWS_FOR_SHIFT = 200   # below this, PSI is dominated by sampling noise


def psi(ref: pd.Series, cur: pd.Series, bins: int = 10) -> float:
    ref = pd.to_numeric(ref, errors="coerce").dropna()
    cur = pd.to_numeric(cur, errors="coerce").dropna()
    if len(ref) < 20 or len(cur) < 20:
        return 0.0
    edges = np.unique(np.quantile(ref, np.linspace(0, 1, bins + 1)))
    edges[0], edges[-1] = -np.inf, np.inf
    r = np.histogram(ref, edges)[0] / len(ref)
    c = np.histogram(cur, edges)[0] / len(cur)
    r, c = np.clip(r, 1e-4, None), np.clip(c, 1e-4, None)
    return float(np.sum((c - r) * np.log(c / r)))


def cat_psi(ref: pd.Series, cur: pd.Series) -> float:
    cats = sorted(set(ref.dropna().astype(str)) | set(cur.dropna().astype(str)))
    r = ref.astype(str).value_counts(normalize=True).reindex(cats).fillna(0).to_numpy()
    c = cur.astype(str).value_counts(normalize=True).reindex(cats).fillna(0).to_numpy()
    r, c = np.clip(r, 1e-4, None), np.clip(c, 1e-4, None)
    return float(np.sum((c - r) * np.log(c / r)))


def train_baseline(ws: Workspace) -> dict[str, Any]:
    """Fit the incumbent on the frozen train role and the reviewed challenger (if
    any). Returns artifact digests."""
    import joblib
    pack = ws.pack()
    train = ws.rows("train")
    target = pack["target"]
    cfg = pack.get("incumbent_pipeline") or pack["pipeline"]
    model = mlcore.build_pipeline(cfg)
    feats = cfg["numeric"] + cfg["categorical"]
    model.fit(train[feats], train[target].astype(int))
    joblib.dump(model, ws.model_path("incumbent"))
    digests = {"incumbent.joblib": mlcore.sha256_file(ws.model_path("incumbent"))}
    ch = pack.get("challenger")
    if ch:
        ccfg = dict(cfg, model=ch["model"], class_weight=ch.get("class_weight"))
        tr = train
        ex = ch.get("exclude_segment")
        if ex:
            tr = tr[tr[ex["column"]].astype(str) != str(ex["value"])]
        cm = mlcore.build_pipeline(ccfg, features=ch["features"])
        cm.fit(tr[ch["features"]], tr[target].astype(int))
        joblib.dump(cm, ws.model_path("challenger"))
        digests["challenger.joblib"] = mlcore.sha256_file(ws.model_path("challenger"))
    return digests


class _Ids:
    def __init__(self) -> None:
        self.n = 0

    def __call__(self) -> str:
        self.n += 1
        return f"F{self.n:02d}"


def _sanitize_error(exc: BaseException) -> dict[str, Any]:
    """Keep only the exception class, the library object and the offending keyword
    — never file paths, data values or environment details."""
    msg = str(exc)
    kw = re.search(r"unexpected keyword argument '([A-Za-z_][A-Za-z0-9_]*)'", msg)
    obj = re.search(r"([A-Z][A-Za-z]+)\.__init__\(\)", msg)
    return {"exception": type(exc).__name__, "object": obj.group(1) if obj else None,
            "keyword": kw.group(1) if kw else None,
            "message": msg[:200] if kw else f"{type(exc).__name__} during pipeline construction"}


_EXC = re.compile(r"\b([A-Z][A-Za-z]*(?:Error|Exception|Warning))\b")


def sanitize_error_text(text: str) -> dict[str, Any]:
    """Same contract as _sanitize_error, for a pasted log: exception class, library object
    and offending keyword only. Paths, values and the rest of the message are dropped."""
    text = text[-6000:]
    exc = _EXC.findall(text)
    kw = re.search(r"unexpected keyword argument '([A-Za-z_][A-Za-z0-9_]*)'", text)
    obj = re.search(r"([A-Z][A-Za-z]+)\.__init__\(\)", text)
    return {"exception": exc[-1] if exc else None, "object": obj.group(1) if obj else None,
            "keyword": kw.group(1) if kw else None,
            "message": (f"{obj.group(1)}.__init__() got an unexpected keyword argument '{kw.group(1)}'"
                        if (kw and obj) else (exc[-1] if exc else "unparsed log"))}


def profile(ws: Workspace) -> list[Finding]:
    pack = ws.pack()
    target, metric = pack["target"], pack["primary_metric"]
    ref, cur = ws.reference(), ws.current()
    cfg = pack.get("incumbent_pipeline") or pack["pipeline"]
    feats = cfg["numeric"] + cfg["categorical"]
    nid = _Ids()
    out: list[Finding] = []

    # schema
    missing_cols = [c for c in feats if c not in cur.columns]
    out.append(Finding(finding_id=nid(), kind="schema", title="Feature schema matches contract"
                       if not missing_cols else "Columns missing from current window",
                       value={"missing_columns": missing_cols}, method="column-set comparison",
                       sample_count=len(cur), severity="critical" if missing_cols else "info"))

    # labels
    n_lab = int(cur[target].notna().sum())
    out.append(Finding(finding_id=nid(), kind="labels", title=f"{n_lab} labelled rows in current window",
                       value={"labelled": n_lab, "total": len(cur)}, method="non-null target count",
                       sample_count=len(cur), severity="warn" if n_lab < 400 else "info"))

    # incumbent performance
    inc = ws.incumbent()
    trained_thr = float(cfg["threshold"])
    rv = ws.rows("ref_validation")
    # "healthy" = the incumbent as validated at training time (trained threshold)
    ref_scores = mlcore.score(rv[target], mlcore.predict_proba(inc, rv), trained_thr)
    sel = ws.rows("selection_validation")
    cur_scores = (mlcore.score(sel[target], mlcore.predict_proba(inc, sel), inc.threshold)
                  if len(sel) >= 20 and sel[target].nunique() > 1 else None)
    if cur_scores:
        drop = round(ref_scores[metric] - cur_scores[metric], 4)
        sev = "critical" if drop > 0.08 else "warn" if drop > 0.03 else "info"
        out.append(Finding(finding_id=nid(), kind="metric_drop",
                           title=f"Incumbent {metric} {ref_scores[metric]:.3f} → {cur_scores[metric]:.3f}",
                           value={"reference": ref_scores, "current": cur_scores, "drop": drop},
                           method=f"incumbent on ref_validation @trained thr={trained_thr} vs "
                                  f"selection_validation @serving thr={inc.threshold}",
                           sample_count=len(sel), severity=sev))
    else:
        out.append(Finding(finding_id=nid(), kind="metric_unavailable",
                           title="Current quality cannot be measured (labels missing or too few)",
                           value={"reference": ref_scores, "labelled_selection_rows": len(sel)},
                           method="label availability check", sample_count=len(sel), severity="warn"))

    # prevalence
    if n_lab:
        pr, pc = float(ref[target].mean()), float(cur[target].dropna().mean())
        d = round(pc - pr, 4)
        out.append(Finding(finding_id=nid(), kind="prevalence",
                           title=f"Positive rate {pr:.1%} → {pc:.1%}", value={"reference": round(pr, 4),
                           "current": round(pc, 4), "delta": d}, method="label mean",
                           sample_count=n_lab, severity="warn" if abs(d) > 0.05 else "info"))

    # distribution shift
    shifts = {}
    for c in cfg["numeric"]:
        if c in cur.columns:
            shifts[c] = round(psi(ref[c], cur[c]), 4)
    for c in cfg["categorical"]:
        if c in cur.columns:
            shifts[c] = round(cat_psi(ref[c], cur[c]), 4)
    top = sorted(shifts.items(), key=lambda kv: -kv[1])
    worst = top[0][1] if top else 0.0
    reliable = len(cur) >= MIN_ROWS_FOR_SHIFT
    out.append(Finding(finding_id=nid(), kind="feature_shift",
                       title=(f"Largest PSI: {top[0][0]} = {worst:.2f}" if top else "No features")
                             + ("" if reliable else f" (unreliable: only {len(cur)} rows)"),
                       value={"psi": dict(top), "reliable": reliable},
                       method="population stability index, ref-quantile bins",
                       sample_count=len(cur), severity="info" if not reliable else "critical" if worst > PSI_CRIT
                       else "warn" if worst > PSI_WARN else "info"))

    # missingness + unseen categories
    miss = {c: round(float(cur[c].isna().mean() - ref[c].isna().mean()), 4) for c in feats if c in cur.columns}
    mmax = max(miss.values()) if miss else 0.0
    out.append(Finding(finding_id=nid(), kind="missingness",
                       title=f"Max missing-rate increase {mmax:.0%}", value={"increase": miss},
                       method="null-rate difference", sample_count=len(cur),
                       severity="critical" if mmax > 0.2 else "warn" if mmax > 0.05 else "info"))
    unseen = {c: sorted(set(cur[c].dropna().astype(str)) - set(ref[c].dropna().astype(str)))
              for c in cfg["categorical"] if c in cur.columns}
    unseen = {k: v for k, v in unseen.items() if v}
    out.append(Finding(finding_id=nid(), kind="unseen_categories",
                       title="Unseen categories present" if unseen else "No unseen categories",
                       value=unseen, method="category set difference", sample_count=len(cur),
                       severity="critical" if unseen else "info"))

    # serving threshold vs trained
    if abs(inc.threshold - trained_thr) > 1e-9:
        out.append(Finding(finding_id=nid(), kind="config_change",
                           title=f"Serving threshold {inc.threshold} differs from trained {trained_thr}",
                           value={"serving": inc.threshold, "trained": trained_thr},
                           method="config diff", sample_count=0, severity="warn"))

    # retrain configuration: build it for real
    built_error = None
    try:
        mlcore.build_pipeline(pack["pipeline"])
    except Exception as exc:  # noqa: BLE001 — any construction error is the finding
        built_error = exc
    if built_error is None and pack.get("error_log"):
        # User-supplied log from their own pipeline: parse library identifiers only.
        info = sanitize_error_text(pack["error_log"])
        if info["exception"]:
            out.append(Finding(finding_id=nid(), kind="pipeline_error",
                               title=f"Submitted error log: {info['exception']}"
                                     + (f" on {info['object']}({info['keyword']}=…)" if info["keyword"] else ""),
                               value=info, method="parsed from the submitted error log (identifiers only)",
                               sample_count=0, severity="critical"))
    if built_error is not None:
        exc = built_error
        info = _sanitize_error(exc)
        out.append(Finding(finding_id=nid(), kind="pipeline_error",
                           title=f"Retrain pipeline fails: {info['exception']}"
                                 + (f" on {info['object']}({info['keyword']}=…)" if info["keyword"] else ""),
                           value=info, method="construct retrain pipeline from deployed config",
                           sample_count=0, severity="critical"))

    env = pack.get("environment") or {}
    prev = env.get("previous") or {}
    changed = {k: {"from": v, "to": env.get(k)} for k, v in prev.items() if env.get(k) != v}
    if changed:
        out.append(Finding(finding_id=nid(), kind="dependency_change",
                           title="Dependency versions changed: " + ", ".join(
                               f"{k} {v['from']}→{v['to']}" for k, v in changed.items()),
                           value=changed, method="environment lock diff", sample_count=0, severity="warn"))

    # segment spread (labelled only)
    seg = pack.get("critical_segment")
    if cur_scores and seg and seg["column"] in sel.columns:
        p = mlcore.predict_proba(inc, sel)
        rows = {}
        for v in sorted(sel[seg["column"]].dropna().astype(str).unique()):
            m = (sel[seg["column"]].astype(str) == v).to_numpy()
            if m.sum() >= 30 and sel[target][m].nunique() > 1:
                rows[v] = mlcore.score(sel[target][m], p[m], inc.threshold)[seg["metric"]]
        spread = round(max(rows.values()) - min(rows.values()), 4) if len(rows) > 1 else 0.0
        out.append(Finding(finding_id=nid(), kind="segment_spread",
                           title=f"{seg['metric']} by {seg['column']}: spread {spread:.2f}",
                           value={"by_segment": rows, "spread": spread}, method="per-segment metric",
                           sample_count=len(sel), severity="warn" if spread > 0.2 else "info"))

    ch = pack.get("challenger")
    if ch:
        undeclared = [f for f in ch["features"] if f not in feats + cfg.get("optional_features", [])]
        out.append(Finding(finding_id=nid(), kind="challenger_claim",
                           title=f"Challenger '{ch['name']}' claims {ch['claimed_metric']}",
                           value={"claimed_metric": ch["claimed_metric"], "declared_split": ch["split"],
                                  "undeclared_features": undeclared, "model": ch["model"]},
                           method="challenger manifest", sample_count=0,
                           severity="warn" if undeclared or ch["split"] != "same" else "info"))
    return out
